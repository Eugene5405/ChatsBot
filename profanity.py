"""Поиск мата по корням слов (ловит формы, приставки, обходы вроде х.у.й и хууууй)."""
import re

BAD_PATTERN = re.compile(
    r"хуй|хуе|хуи|хуя|хую|хуев|хер[ан]?\b|"
    r"пизд|пезд|"
    r"бля[дт]|блеа|"
    r"(?<![нлбдр])еб(?:ат|ал|ан|аш|ну|ун|уч|ыр|ис|ло|ли|ля)|"
    r"\bеб[ауое]\b|"
    r"(?:на|за|у|вы|от|по|до|съ|подъ|разъ|объ)еб|"
    r"муда[кч]|залуп|гондон|пидор|пидар|манда\b"
)

LOOKALIKES = str.maketrans({"x": "х", "y": "у", "e": "е", "a": "а", "o": "о", "p": "р", "c": "с", "b": "б", "ё": "е"})


def has_bad_word(text: str) -> bool:
    t = text.lower().translate(LOOKALIKES)
    t = re.sub(r"[^а-я\s]", "", t)
    t = re.sub(r"(.)\1+", r"\1", t)
    return bool(BAD_PATTERN.search(t))
